export function translateUiPhrase(source: string, locale: Locale): string {
  if (locale === 'en') return source;
  const normalized = source.replace(/\s+/g, ' ').trim();
  const translated = phrases[normalized]?.[locale];
  return translated ?? source;
}

export function hasUiPhrase(source: string): boolean {
  return source.replace(/\s+/g, ' ').trim() in phrases;
}
